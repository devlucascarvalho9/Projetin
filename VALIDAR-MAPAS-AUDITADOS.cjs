const fs=require('fs'),path=require('path');
const root=__dirname;
const readJson=r=>JSON.parse(fs.readFileSync(path.join(root,r),'utf8').replace(/^\uFEFF/,''));
const fail=m=>{console.error('[FALHA] '+m);process.exitCode=1};
const ok=m=>console.log('[OK] '+m);
const world=readJson('packages/server/data/map/world.json');
const client=readJson('packages/client/data/maps/map.json');
const W=world.width;
if(W===1152&&world.height===1152&&world.tileSize===16) ok('world 1152x1152 / tile 16'); else fail('dimensoes do world inesperadas');
const ts=(client.tilesets||[]).find(t=>t.relativePath==='mapa-amor-nativo.png');
