const atlas='packages/client/dist/img/tilesets/mapa-amor-nativo.png';
if(fs.existsSync(path.join(root,atlas))&&fs.statSync(path.join(root,atlas)).size>3000000) ok('atlas nativo presente no dist'); else fail('atlas nativo ausente/invalido no dist');
function tile(x,y){return world.data[y*W+x]}
const coll=new Set(world.collisions||[]);
const love=[];for(let y=1056;y<1068;y++)for(let x=384;x<400;x++)love.push(tile(x,y));
if(love.length===192&&new Set(love).size===192&&Math.min(...love)===19152&&Math.max(...love)===19343) ok('Mapa Amor nativo 16x12 instalado'); else fail('dados nativos do Amor incorretos');
const cave=[];for(let y=1056;y<1120;y++)for(let x=480;x<560;x++)cave.push(tile(x,y));
if(cave.length===5120&&new Set(cave).size===5120&&Math.min(...cave)===19408&&Math.max(...cave)===24527) ok('Caverna nativa 80x64 instalada'); else fail('dados nativos da caverna incorretos');
const blocked=cave.filter(g=>coll.has(g)).length;
if(blocked===2999) ok('Caverna: 2999 tiles blocking preservados'); else fail('blocking da caverna: esperado 2999, encontrado '+blocked);
if(!coll.has(tile(392,1062))) ok('spawn /amor caminhavel'); else fail('spawn /amor bloqueado');
if(!coll.has(tile(517,1088))) ok('spawn /carverna caminhavel'); else fail('spawn /carverna bloqueado');
const cmd=fs.readFileSync(path.join(root,'packages/server/src/controllers/commands.ts'),'utf8');
if(cmd.includes("case 'carverna':")&&cmd.includes('teleport(517, 1088')&&cmd.includes('teleport(392, 1062')) ok('comandos /amor e /carverna apontam para os mapas auditados'); else fail('comandos nao estao na versao auditada');
const bundle=fs.readFileSync(path.join(root,'packages/client/dist/_astro/hoisted.auditnative.v1.js'),'utf8');
if(bundle.includes('firstGid:19152,lastGid:25339')&&bundle.includes('mapa-amor-nativo.png')) ok('runtime do navegador conhece o atlas nativo'); else fail('runtime do navegador nao conhece o atlas');
const wrapper=fs.readFileSync(path.join(root,'packages/client/dist/_astro/hoisted.f2a29915.js'),'utf8').trim();
if(wrapper==='import"./hoisted.auditnative.v1.js";') ok('entrada do client aponta para bundle auditado'); else fail('entrada do client ainda aponta para bundle antigo');
const sp=readJson('packages/server/package.json').scripts.start;
const cp=readJson('packages/client/package.json').scripts.start;
if(sp.includes('src/main.ts')) ok('server inicia pelo source atualizado'); else fail('server ainda inicia dist antigo');
if(cp.includes('9010')&&cp.includes('--dev')) ok('client inicia em porta limpa 9010 sem cache de producao'); else fail('client nao esta na porta auditada 9010');
if(!process.exitCode) console.log('\nVALIDACAO COMPLETA: mapas auditados prontos.');
